/** Translate an API crop name using i18n. Falls back to the raw name. */
export function translateCropName(t: (key: string, opts?: Record<string, unknown>) => string, apiName: string): string {
  const i18nKey = CROP_NAME_KEYS[apiName];
  return i18nKey ? t(i18nKey, { defaultValue: apiName }) : apiName;
}
